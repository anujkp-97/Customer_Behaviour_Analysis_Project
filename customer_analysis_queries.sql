-- 7. Top 5 products with highest discount usage %

SELECT 
	item_purchased, 
    count(item_purchased) as total_item_sold,
    count(case when discount_applied='Yes' Then 1 end) as sold_when_discount_applied,
        count(case when discount_applied='Yes' Then 1 end) *100.0/ COUNT(*) as discount_percent
