-- 4. Which customer used a discount but still spent more then the average purchase amount?

SELECT 
	customer_id,
    purchase_amount,
    discount_applied
FROM customer_data
where discount_applied= "Yes" AND purchase_amount > (SELECT AVG(purchase_amount) FROM customer_data)
LIMIT 10;

-- ? Business problem:- Company cannot identify high-spending customers who are also discount users.
		
        -- Impact:- 
        -- Identify premium discount-sensitive customers
        -- Improve customer retention and revenue
        -- Enables targeted discount campaign

