-- 8. Segment customer into new, returning and loyal based on their total number of previous purchase, and show the count of each segment

SELECT 
	CASE 
		WHEN previous_purchases = '0' Then 'New Customer'
        WHEN previous_purchases BETWEEN 1 AND 15 THEN 'Returning Customer'
	ELSE 'Loyal Customer'
END As customer_segment,
COUNT(*) as customer_count
FROM customer_data
GROUP BY CASE 
		WHEN previous_purchases = '0' Then 'New Customer'
        WHEN previous_purchases BETWEEN 1 AND 15 THEN 'Returning Customer'
	ELSE 'Loyal Customer'
END;

-- Business Problem :- Lack of customer segmentation leads to generic strategies

-- Impact:- 
			-- Enables personalized marketing
            -- Improves Retentation strategies
            -- Increase conversation rates
            
